"""
ЗАДАЧА 9: МИНИ-ГРАФИЧЕСКИЙ РЕДАКТОР

Объединение всех трех концепций ООП:
1. ИНКАПСУЛЯЦИЯ - скрытые координаты в Figure
2. НАСЛЕДОВАНИЕ - Circle и Square наследуют Figure
3. ПОЛИМОРФИЗМ - calculate_area() для разных типов фигур
"""

class Figure:
    """
    БАЗОВЫЙ КЛАСС Figure
    Реализует ИНКАПСУЛЯЦИЮ - координаты скрыты.
    """
    
    def __init__(self, x, y):
        """
        Конструктор базового класса.
        
        Параметры:
        x (float): координата x
        y (float): координата y
        """
        self._x = x          # СКРЫТЫЕ координаты (инкапсуляция)
        self._y = y          # СКРЫТЫЕ координаты (инкапсуляция)
    
    # Публичные методы для доступа к скрытым данным
    def get_coords(self):
        """
        Публичный метод для получения координат.
        Это ЕДИНСТВЕННЫЙ способ узнать координаты.
        """
        return (self._x, self._y)
    
    def set_coords(self, x, y):
        """
        Публичный метод для изменения координат.
        Это ЕДИНСТВЕННЫЙ способ изменить координаты.
        """
        self._x = x
        self._y = y
    
    def calculate_area(self):
        """
        Метод calculate_area() в базовом классе.
        Будет переопределен в дочерних классах (ПОЛИМОРФИЗМ).
        """
        return 0


class Circle(Figure):
    """
    ДОЧЕРНИЙ КЛАСС Circle (Круг)
    Реализует НАСЛЕДОВАНИЕ от Figure.
    """
    
    def __init__(self, x, y, radius):
        """
        Конструктор класса Circle.
        
        Параметры:
        x (float): координата x центра
        y (float): координата y центра
        radius (float): радиус круга
        """
        # Вызываем конструктор родительского класса (НАСЛЕДОВАНИЕ)
        super().__init__(x, y)
        self.radius = radius
    
    def calculate_area(self):
        """
        Переопределяем метод calculate_area() для круга.
        Реализует ПОЛИМОРФИЗМ.
        """
        import math
        return math.pi * self.radius ** 2
    
    def __str__(self):
        """Красивый вывод для круга."""
        coords = self.get_coords()
        return f"Круг: центр {coords}, радиус {self.radius}, площадь {self.calculate_area():.2f}"


class Square(Figure):
    """
    ДОЧЕРНИЙ КЛАСС Square (Квадрат)
    Реализует НАСЛЕДОВАНИЕ от Figure.
    """
    
    def __init__(self, x, y, side):
        """
        Конструктор класса Square.
        
        Параметры:
        x (float): координата x левого верхнего угла
        y (float): координата y левого верхнего угла
        side (float): длина стороны квадрата
        """
        # Вызываем конструктор родительского класса (НАСЛЕДОВАНИЕ)
        super().__init__(x, y)
        self.side = side
    
    def calculate_area(self):
        """
        Переопределяем метод calculate_area() для квадрата.
        Реализует ПОЛИМОРФИЗМ.
        """
        return self.side ** 2
    
    def __str__(self):
        """Красивый вывод для квадрата."""
        coords = self.get_coords()
        return f"Квадрат: угол {coords}, сторона {self.side}, площадь {self.calculate_area():.2f}"


