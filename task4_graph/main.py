# Задача 4: Класс Graph с инкапсуляцией
class Graph:
    """
    Класс Graph с инкапсуляцией координат и масштаба.
    Это пример из теории про графики функций.
    """
    
    def __init__(self, x=0, y=0, scale=1.0):
        """
        Конструктор класса. Создает график с начальными координатами и масштабом.
        
        Параметры:
        x (float): начальная координата x
        y (float): начальная координата y
        scale (float): начальный масштаб
        """
        self._x = x          # скрытые координаты (инкапсуляция)
        self._y = y          # скрытые координаты (инкапсуляция)
        self._scale = scale  # скрытый масштаб (инкапсуляция)
    
    def move(self, dx, dy):
        """
        Публичный метод для перемещения графика.
        
        Параметры:
        dx (float): изменение координаты x
        dy (float): изменение координаты y
        """
        self._x += dx
        self._y += dy
        print(f"  График перемещен на ({dx}, {dy})")
    
    def change_scale(self, factor):
        """
        Публичный метод для изменения масштаба графика.
        
        Параметры:
        factor (float): множитель изменения масштаба
        """
        self._scale *= factor
        print(f"  Масштаб графика изменен в {factor} раз")
    
    def get_state(self):
        """
        Публичный метод для получения текущего состояния графика.
        Это единственный способ узнать координаты и масштаб.
        """
        return f"координаты ({self._x}, {self._y}), масштаб: {self._scale}"
    
    def __str__(self):
        """
        Специальный метод для красивого вывода объекта.
        Вызывается при print().
        """
        return f"График: координаты ({self._x}, {self._y}), масштаб: {self._scale}"


