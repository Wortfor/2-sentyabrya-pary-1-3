# Задача 1: Класс Cat
class Cat:
    """Класс Cat представляет кота с породой, именем и возрастом"""
    
    def __init__(self, breed, name, age):
        """Конструктор класса. Создает нового кота."""
        self.breed = breed  # порода
        self.name = name    # имя
        self.age = age      # возраст


# Создаем трех разных котов (объекты класса Cat)
cat1 = Cat("Сиамская", "Барсик", 3)
cat2 = Cat("Британская", "Мурка", 5)
cat3 = Cat("Мейн-кун", "Кейси", 2)

# Выводим информацию о каждом коте
print("Информация о котах:")
print(f"Кот: {cat1.name}, порода: {cat1.breed}, возраст: {cat1.age} лет")
print(f"Кот: {cat2.name}, порода: {cat2.breed}, возраст: {cat2.age} лет")
print(f"Кошка: {cat3.name}, порода: {cat3.breed}, возраст: {cat3.age} лет")