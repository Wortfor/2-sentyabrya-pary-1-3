class Car:
    """
    Класс Car с инкапсуляцией - скрытый атрибут температуры двигателя.
    Это пример инкапсуляции из теории ООП (как автомобиль - скрытые детали).
    """
    
    def __init__(self):
        """
        Конструктор класса.
        Начальная температура двигателя 20 градусов (скрытый атрибут).
        """
        self._engine_temperature = 20  # скрытый атрибут (инкапсуляция)
        print("Автомобиль создан. Температура двигателя: 20°C")
    
    def start_engine(self):
        """
        Публичный метод для прогрева двигателя.
        Увеличивает температуру до 90°C.
        """
        self._engine_temperature = 90
        print("Двигатель прогрет")
    
    def drive(self):
        """
        Публичный метод для поездки.
        Проверяет температуру двигателя перед поездкой.
        Если температура >= 90°C - можно ехать.
        """
        if self._engine_temperature >= 90:
            print("Поехали!")
        else:
            print("Двигатель не прогрет! Сначала запустите start_engine()")


