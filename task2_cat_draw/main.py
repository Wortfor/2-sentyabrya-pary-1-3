# Задача 2: Класс Cat с методом draw()
class Cat:
    """Класс Cat представляет кота с породой, именем и возрастом"""
    
    def __init__(self, breed, name, age):
        """Конструктор класса. Создает нового кота."""
        self.breed = breed  # порода
        self.name = name    # имя
        self.age = age      # возраст
    
    def draw(self):
        """
        Метод draw() выводит сообщение о рисовании кота.
        Это новый метод, добавленный во второй задаче.
        """
        print(f"На экране рисуется кот {self.name}, порода {self.breed}")


# Создаем трех разных котов (объекты класса Cat)
cat1 = Cat("Сиамская", "Барсик", 3)
cat2 = Cat("Британская", "Мурка", 5)
cat3 = Cat("Персидская", "Снежок", 2)

# Выводим информацию о каждом коте (из задачи 1)
print("Информация о котах:")
print(f"Кот: {cat1.name}, порода: {cat1.breed}, возраст: {cat1.age} лет")
print(f"Кот: {cat2.name}, порода: {cat2.breed}, возраст: {cat2.age} лет")
print(f"Кот: {cat3.name}, порода: {cat3.breed}, возраст: {cat3.age} лет")

print("\n" + "="*40 + "\n")

# Вызываем метод draw() для каждого кота (новая функциональность из задачи 2)
print("Рисуем котов:")
cat1.draw()
cat2.draw()
cat3.draw()